__constant__ uint32_t AES_RCON[10] = { 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36 };

__device__ __forceinline__ uint32_t aes_sub_word(uint32_t w) {
    return ((uint32_t)AES_SBOX[(w >> 24) & 0xff] << 24) |
           ((uint32_t)AES_SBOX[(w >> 16) & 0xff] << 16) |
           ((uint32_t)AES_SBOX[(w >> 8) & 0xff] << 8) |
           ((uint32_t)AES_SBOX[w & 0xff]);
}

__device__ __forceinline__ uint32_t aes_rot_word(uint32_t w) {
    return (w << 8) | (w >> 24);
}

__device__ __forceinline__ uint32_t aes_xtimes(uint32_t b) {
    return ((b << 1) ^ (((b >> 7) & 1) * 0x11b)) & 0xff;
}

__device__ __forceinline__ uint32_t aes_mix_col(uint32_t col) {
    uint32_t a0 = (col >> 24) & 0xff;
    uint32_t a1 = (col >> 16) & 0xff;
    uint32_t a2 = (col >> 8) & 0xff;
    uint32_t a3 = col & 0xff;

    uint32_t r0 = aes_xtimes(a0) ^ aes_xtimes(a1) ^ a1 ^ a2 ^ a3;
    uint32_t r1 = a0 ^ aes_xtimes(a1) ^ aes_xtimes(a2) ^ a2 ^ a3;
    uint32_t r2 = a0 ^ a1 ^ aes_xtimes(a2) ^ aes_xtimes(a3) ^ a3;
    uint32_t r3 = aes_xtimes(a0) ^ a0 ^ a1 ^ a2 ^ aes_xtimes(a3);

    return (r0 << 24) | (r1 << 16) | (r2 << 8) | r3;
}

__device__ void aes256_key_expansion(const uint8_t key[32], uint32_t rk[15][4]) {
    uint32_t w[60];
    for (int i = 0; i < 8; i++) {
        w[i] = ((uint32_t)key[i * 4 + 0] << 24) |
               ((uint32_t)key[i * 4 + 1] << 16) |
               ((uint32_t)key[i * 4 + 2] << 8)  |
               ((uint32_t)key[i * 4 + 3]);
    }
    for (int i = 8; i < 60; i++) {
        uint32_t temp = w[i - 1];
        if (i % 8 == 0) {
            temp = aes_sub_word(aes_rot_word(temp)) ^ (AES_RCON[(i / 8) - 1] << 24);
        } else if (i % 8 == 4) {
            temp = aes_sub_word(temp);
        }
        w[i] = w[i - 8] ^ temp;
    }
    for (int r = 0; r < 15; r++) {
        for (int c = 0; c < 4; c++) {
            rk[r][c] = w[r * 4 + c];
        }
    }
}

__device__ void aes256_encrypt_block(const uint32_t rk[15][4], const uint32_t in[4], uint32_t out[4]) {
    uint32_t s0 = in[0] ^ rk[0][0];
    uint32_t s1 = in[1] ^ rk[0][1];
    uint32_t s2 = in[2] ^ rk[0][2];
    uint32_t s3 = in[3] ^ rk[0][3];

    for (int r = 1; r < 15; r++) {
        uint32_t sb0 = aes_sub_word(s0);
        uint32_t sb1 = aes_sub_word(s1);
        uint32_t sb2 = aes_sub_word(s2);
        uint32_t sb3 = aes_sub_word(s3);

        uint32_t b00 = (sb0 >> 24) & 0xff; uint32_t b10 = (sb0 >> 16) & 0xff; uint32_t b20 = (sb0 >> 8) & 0xff; uint32_t b30 = sb0 & 0xff;
        uint32_t b01 = (sb1 >> 24) & 0xff; uint32_t b11 = (sb1 >> 16) & 0xff; uint32_t b21 = (sb1 >> 8) & 0xff; uint32_t b31 = sb1 & 0xff;
        uint32_t b02 = (sb2 >> 24) & 0xff; uint32_t b12 = (sb2 >> 16) & 0xff; uint32_t b22 = (sb2 >> 8) & 0xff; uint32_t b32 = sb2 & 0xff;
        uint32_t b03 = (sb3 >> 24) & 0xff; uint32_t b13 = (sb3 >> 16) & 0xff; uint32_t b23 = (sb3 >> 8) & 0xff; uint32_t b33 = sb3 & 0xff;

        uint32_t sr0 = (b00 << 24) | (b11 << 16) | (b22 << 8) | b33;
        uint32_t sr1 = (b01 << 24) | (b12 << 16) | (b23 << 8) | b30;
        uint32_t sr2 = (b02 << 24) | (b13 << 16) | (b20 << 8) | b31;
        uint32_t sr3 = (b03 << 24) | (b10 << 16) | (b21 << 8) | b32;

        if (r < 14) {
            s0 = aes_mix_col(sr0) ^ rk[r][0];
            s1 = aes_mix_col(sr1) ^ rk[r][1];
            s2 = aes_mix_col(sr2) ^ rk[r][2];
            s3 = aes_mix_col(sr3) ^ rk[r][3];
        } else {
            s0 = sr0 ^ rk[r][0];
            s1 = sr1 ^ rk[r][1];
            s2 = sr2 ^ rk[r][2];
            s3 = sr3 ^ rk[r][3];
        }
    }
    out[0] = s0; out[1] = s1; out[2] = s2; out[3] = s3;
}
